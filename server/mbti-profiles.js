export function generateDebateResponse(typeId, topic, history) {
  const profile = mbtiProfiles.find(p => p.id === typeId)
  if (!profile) return { content: `关于"${topic}"，这是一个值得讨论的话题。`, confidence: 50 }

  const templates = responseTemplates[typeId]
  if (!templates) return { content: `关于"${topic}"，我觉得这很有意思。`, confidence: 50 }

  const previousEntry = history.length > 0 ? history[history.length - 1] : null
  const sameTypeCount = history.filter(h => h.typeId === typeId).length

  let responses = templates(topic)

  // If responding to someone
  if (previousEntry && !previousEntry.isUser && previousEntry.typeId !== typeId) {
    const typeReactions = reactionTemplates[typeId]?.[previousEntry.typeId]
    if (typeReactions) {
      responses = [...typeReactions, ...responses]
    } else {
      responses = [
        `@${previousEntry.typeId} 你说得有道理，但我想从另一个角度补充一下...`,
        `听了 @${previousEntry.typeId} 的发言，我有一个不同的看法。`,
        ...responses
      ]
    }
  }

  const index = Math.min(sameTypeCount, responses.length - 1)
  const content = responses[index] || responses[responses.length - 1]

  const baseConfidence = confidenceBases[typeId] || 60
  const variation = Math.floor(Math.random() * 20 - 10)
  const confidence = Math.min(95, Math.max(30, baseConfidence + variation))

  return { content, confidence }
}

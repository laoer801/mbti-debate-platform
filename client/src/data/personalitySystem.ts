/**
 * 生成辩论时注入的动态上下文
 */
export function buildDynamicContext(
  typeId: string,
  topic: string,
  history: { typeId: string; content: string; isUser?: boolean }[],
  sceneName?: string,
  stance?: string
): string {
  const sys = personalitySystems[typeId]
  if (!sys) return ''

  const lastEntries = history.slice(-3)
  const othersSaid = lastEntries
    .filter(h => h.typeId !== typeId)
    .map(h => `[${h.typeId}]：${h.content}`)
    .join('\n')

  const myLast = lastEntries.filter(h => h.typeId === typeId).pop()

  let context = `## 当前辩论话题
${topic}

## 你的性格是 ${typeId}
${sys.systemPrompt.split('\n').slice(1, 3).join(' ')}`

  if (sceneName) {
    context += `\n\n## 当前场景
${sceneName}`
  }

  if (stance) {
    context += `\n## 你的立场
${stance}`
  }

  if (othersSaid) {
    context += `\n\n## 前面其他人说了什么
${othersSaid}`
  }

  if (myLast) {
    context += `\n\n## 你刚才说了
${myLast.content}`
  }

  context += `\n\n## 请基于你的人格特征发言
- 你说的话必须符合你的认知模式和价值观
- 注意你的说话风格（语气：${sys.speechPattern.tone}）
- 如果前面有人论点有漏洞，以你的人格方式指出
- 保持人设稳定，不要跳出角色`

  return context
}

/**
 * 三层架构：16 种 MBTI 人格的完整语言系统
 *
 * 第一层 — System Prompt：定义"我是谁"（身份画像 + 认知模式 + 说话风格 + 价值观 + 盲点）
 * 第二层 — Few-shot Examples：教会"怎么说话"（每种人格 3-5 组典型对话示例）
 * 第三层 — Dynamic Context：在互动中保持人设（场景注入 + 对方观点感知 + 立场提示）
 *
 * 参考：苏黎世联邦理工学院 MBTI-in-Thoughts 框架
 */

/* ======================== 类型定义 ======================== */

export interface SpeechPattern {
  tone: string           // 语气描述
  wordPreference: string // 用词偏好
  typicalSentence: string // 典型句式
  emotionExpression: string // 情绪表达方式
  avgSentenceLength: number // 平均句长（字）
}

export interface CognitiveMode {
  energySource: string    // 能量来源 E/I
  infoProcess: string     // 信息处理 S/N
  decisionStyle: string   // 决策方式 T/F
  lifeStyle: string       // 生活方式 J/P
}

export interface FewShotExample {
  scenario: string        // 场景描述
  userSays: string        // 用户说的话
  response: string        // 该人格的回复
}

export interface PersonalitySystem {
  typeId: string
  systemPrompt: string    // 第一层：完整系统提示词
  cognitiveMode: CognitiveMode
  speechPattern: SpeechPattern
  values: string[]        // 核心价值观
  blindSpots: string[]    // 性格盲点
  fewShotExamples: FewShotExample[] // 第二层：少样本示例
  debateStances: string[] // 辩论中可能的立场
  reflectionTriggers: string[] // 触发自反思的场景
}


/**
 * 从关键词池中提取所有词
 */
const ALL_KEYWORDS = DEBATE_EXAMPLES.flatMap((e) =>
  [e.topic, e.field, ...e.strategy, ...e.types].flatMap((s) => s.split(/[\s,，、]+/)),
)

/**
 * 按辩题关键词匹配好辩论示例
 * @param topic 当前辩题
 * @param limit 最多返回几组（默认 2）
 * @returns 匹配度最高的示例数组
 */
export function findExamplesForTopic(topic: string, limit = 2): DebateExample[] {
  const topicWords = topic.split(/[\s,，、：:；;。.?？]+/).filter((w) => w.length >= 2)

  const scored = DEBATE_EXAMPLES.map((ex) => {
    let score = 0
    const hay = `${ex.topic} ${ex.field} ${ex.strategy.join(' ')} ${ex.types.join(' ')}`

    // 辩题直接词匹配
    for (const w of topicWords) {
      if (hay.includes(w)) score += 3
    }

    // 领域关键词匹配
    for (const s of ex.strategy) {
      if (topic.includes(s) || s.includes(topic.slice(0, 2))) score += 2
    }

    return { ex, score }
  })

  scored.sort((a, b) => b.score - a.score)
  const result = scored.filter((s) => s.score > 0).slice(0, limit).map((s) => s.ex)

  // 如果没有匹配到任何示例，返回前 limit 个（默认池）
  return result.length > 0 ? result : DEBATE_EXAMPLES.slice(0, limit)
}

/**
 * 随机取一组示例（用于多样化注入）
 */
export function randomExample(): DebateExample {
  return DEBATE_EXAMPLES[Math.floor(Math.random() * DEBATE_EXAMPLES.length)]
}

const LEXICON: string[] = buildLexicon()
const LEXICON_SET = new Set(LEXICON)

// ============ 文本归一化 ============

/** 把文本切成「句子片段」：按标点/空白拆分，保留中文串与英文/数字串 */
function splitIntoTokens(text: string): string[] {
  const parts = text
    .toLowerCase()
    // 统一中英文标点为空白
    .replace(/[，。！？；：、,.!?;:"'“”‘’（）()\[\]【】<>《》\s+/\\|=_~`@#$%^&*\-—…·]+/g, ' ')
    .split(/\s+/)
    .filter(p => p.length > 0)
  return parts
}

/**
 * 对一段中文文本分词，返回 token 数组（已去停用词、去单字噪声）。
 *
 * 算法：
 *  - 每个「片段」先尝试词典最长匹配切出领域术语
 *  - 剩余部分按 2-gram 滑窗切出双字 token
 *  - 纯英文/数字 token 原样保留
 *
 * @example
 *   tokenize('如何投资基金') // ['如何', '投资', '基金']（词典命中）
 *   tokenize('量子纠缠原理') // ['量子', '纠缠', '原理']（词典+2gram 混合）
 */
export function tokenize(text: string): string[] {
  const out: string[] = []
  const seen = new Set<string>()
  const push = (t: string) => {
    if (t.length < 2) return                 // 单字噪声
    if (STOP_WORDS.has(t)) return            // 停用词
    if (seen.has(t)) return                  // 去重（同段）
    seen.add(t)
    out.push(t)
  }

  for (const part of splitIntoTokens(text)) {
    // 纯英文/数字：直接作为 token（可能带大小写归一）
    if (/^[a-z0-9]+$/.test(part)) {
      if (part.length >= 2) push(part)
      continue
    }

    // 中文片段：词典最长匹配 + 2-gram 回退
    let i = 0
    const len = part.length
    while (i < len) {
      // 尝试最长词典匹配（最多 6 字）
      let matched = false
      for (let size = Math.min(6, len - i); size >= 2; size--) {
        const word = part.slice(i, i + size)
        if (LEXICON_SET.has(word)) {
          push(word)
          i += size
          matched = true
          break
        }
      }
      if (matched) continue

      // 未命中：取当前位置开始的 2-gram 作为 token，前进 1 字（滑窗）
      if (i + 1 < len) {
        push(part.slice(i, i + 2))
      }
      i += 1
    }
  }

  return out
}

/** 查询分词：与索引分词一致，但保留更细粒度（查询词短，2-gram 合理） */
export function tokenizeQuery(text: string): string[] {
  return tokenize(text)
}

/** 统计词频（token → 次数） */
export function countTokens(tokens: string[]): Map<string, number> {
  const map = new Map<string, number>()
  for (const t of tokens) map.set(t, (map.get(t) ?? 0) + 1)
  return map
}

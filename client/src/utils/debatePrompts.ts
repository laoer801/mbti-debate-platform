// ============ 三点九、经典辩论案例库（v27.2「辩论视频/名场面知识化」） ============

/**
 * 生成「经典辩论案例」段落（注入系统提示词）：
 * 从 debateCases 中按辩题关键词匹配最相关的真实辩论赛/名场面，
 * 提示 LLM 在合适时机引用——「1993 年国际大专辩论赛上，蒋昌建说过……」
 * 无匹配时随机给 1 个通用案例，保证有料可引。
 */
export function buildCaseSection(topic: string): string {
  const cases = findCasesForTopic(topic, 2)
  const picked = cases.length > 0 ? cases : [randomCase()]
  const body = picked
    .map(c => {
      const side = `正：${c.proPoints.join(' / ')}\n反：${c.conPoints.join(' / ')}`
      const quote = c.quotes[0]
      return `【${c.source}｜辩题「${c.topic}」】
${side}
金句：「${quote}」
点评：${c.note}`
    })
    .join('\n\n')
  return `## 经典辩论案例（真实发生过的辩论赛/名场面，可引用须标明出处）
以下是与辩题相关的真实辩论案例。引用格式：「正如 ${picked[0]?.source} 那场辩论所示，……」或直接引用金句（须注明出自谁之口）。用案例不是为了堆砌，而是用「前人的交锋」支撑你的论点或反驳对方。
${body}`
}

